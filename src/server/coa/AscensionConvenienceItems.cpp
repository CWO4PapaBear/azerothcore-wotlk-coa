class spell_area52_vanity_beast_whistle : public SpellScript
{
    PrepareSpellScript(spell_area52_vanity_beast_whistle);

    uint32 creatureEntry = 0;

    bool Load() override
    {
        Item* item = GetCastItem();
        if (!item)
            return false;
        auto it = std::lower_bound(std::begin(BeastWhistles), std::end(BeastWhistles), item->GetEntry(),
            [](BeastWhistle const& row, uint32 entry) { return row.item < entry; });
        if (it == std::end(BeastWhistles) || it->item != item->GetEntry() || it->spell != GetSpellInfo()->Id)
            return false;
        creatureEntry = it->creature;
        return true;
    }

    bool Validate(SpellInfo const* info) override
    {
        return info->Effects[EFFECT_0].Effect == SPELL_EFFECT_DUMMY;
    }

    SpellCastResult CheckCast()
    {
        Player* player = GetCaster()->ToPlayer();
        CreatureTemplate const* creature = sObjectMgr->GetCreatureTemplate(creatureEntry);
        if (!player || !creature || !creature->IsTameable(player->CanTameExoticPets()))
            return SPELL_FAILED_BAD_TARGETS;
        if (player->GetPetGUID() || player->GetCharmGUID() || player->IsExistPet())
            return SPELL_FAILED_ALREADY_HAVE_SUMMON;
        return SPELL_CAST_OK;
    }

    void Tame(SpellEffIndex effect)
    {
        PreventHitDefaultEffect(effect);
        if (Player* player = GetCaster()->ToPlayer())
            player->CreatePet(creatureEntry, GetSpellInfo()->Id);
    }

    void Register() override
    {
        OnCheckCast += SpellCheckCastFn(spell_area52_vanity_beast_whistle::CheckCast);
        OnEffectHitTarget += SpellEffectFn(spell_area52_vanity_beast_whistle::Tame, EFFECT_0, SPELL_EFFECT_DUMMY);
    }
};

class spell_ascension_flight_masters_whistle : public SpellScript
{
    PrepareSpellScript(spell_ascension_flight_masters_whistle);

    SpellCastResult Check()
    {
        Player* player = GetCaster()->ToPlayer();
        if (!player || player->GetMap()->Instanceable() || !NearestFlightMaster(player))
            return SPELL_FAILED_NOT_HERE;
        return SPELL_CAST_OK;
    }

    void Retreat(SpellEffIndex)
    {
        Player* player = GetCaster()->ToPlayer();
        if (TaxiNodesEntry const* node = player ? NearestFlightMaster(player) : nullptr)
            player->TeleportTo(node->map_id, node->x, node->y, node->z, player->GetOrientation());
    }

    void Register() override
    {
        OnCheckCast += SpellCheckCastFn(spell_ascension_flight_masters_whistle::Check);
        OnEffectHit += SpellEffectFn(spell_ascension_flight_masters_whistle::Retreat, EFFECT_0, SPELL_EFFECT_DUMMY);
    }
};
