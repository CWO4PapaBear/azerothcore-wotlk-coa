inline bool IsHeirloomCache(std::uint32_t item)
{
    return item >= 1339058 && item <= 1339064;
}

inline std::uint32_t HeirloomCacheForPiece(std::uint32_t item)
{
    static const auto byPiece = []
    {
        std::map<std::uint32_t, std::uint32_t> result;
        for (auto const& [cache, pieces] : Bundles)
            if (IsHeirloomCache(cache))
                for (auto piece : pieces)
                    result.emplace(piece, cache);
        return result;
    }();
    auto itr = byPiece.find(item);
    return itr == byPiece.end() ? 0 : itr->second;
}
